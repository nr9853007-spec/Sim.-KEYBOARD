-- Run this file in Supabase Dashboard -> SQL Editor -> New query.
-- The browser never receives the Supabase secret key. All writes go through the Express server.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  role text not null default 'user' check (role in ('user','admin')),
  banned boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  body text not null check (char_length(body) between 8 and 500),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  place text not null,
  contact text not null,
  details text not null,
  status text not null default 'pending' check (status in ('pending','accepted','rejected','answered')),
  reply text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.reviews enable row level security;
alter table public.tickets enable row level security;

-- No anon/authenticated policies are intentionally created: only the server-side
-- Supabase secret key can access these tables. Never put that key in frontend code.
